"""Publication lookup-table weights for Kitchen vs Fly (V0.3.20).

Stake Engine publishes the RTP computed exactly from the uploaded lookup
table: sum(weight * payout) / sum(weight) / cost (utils/analysis/
distribution_functions.py::calculate_rtp, used by utils/rgs_verification.py).
Simulated books all start with weight 1, so the unit-weight RTP is just the
library's sample mean.

Instead of the official Rust optimizer, which redraws the win distribution
from Gaussian mixtures (non-seeded, see optimization_program/src/main.rs),
the product owner chose (2026-09-25) to keep the simulated distribution
intact:
- every winning book gets the same weight `win_weight`;
- every zero-win book gets the same weight `zero_weight`.

The two integers are chosen so the published RTP equals the declared target
EXACTLY, as a rational number. The relative frequencies of all winning
outcomes (small wins, N2-N5, Fly) are exactly those simulated; only the
share of zero-win rounds, i.e. the hit rate, moves.
"""

from fractions import Fraction
from math import gcd

UINT64_MAX = 2**64 - 1


def zero_win_weights(payouts_cents, target_rtp, cost=1.0):
    """Return (win_weight, zero_weight) integers such that
    sum(w_i * payout_i) / (100 * cost * sum(w_i)) == target_rtp exactly.

    `payouts_cents` are the lookup table's payoutMultiplier values
    (hundredths of the bet). Raises ValueError if the target cannot be reached
    with non-negative weights, or if the weight total would overflow uint64."""
    target = Fraction(str(target_rtp)) * Fraction(str(cost))
    total_cents = sum(payouts_cents)
    wins = sum(1 for p in payouts_cents if p > 0)
    zeros = len(payouts_cents) - wins
    if wins == 0:
        raise ValueError("No winning book: RTP cannot be positive.")
    # RTP = S*w / (100*(W*w + Z*z))  =>  z/w = (S/(100*target) - W) / Z
    ratio_num = Fraction(total_cents, 100) / target - wins
    if ratio_num < 0:
        raise ValueError("Target RTP above the winning books' mean: needs negative zero-win weight.")
    if zeros == 0:
        if ratio_num != 0:
            raise ValueError("No zero-win book to absorb the RTP adjustment.")
        return 1, 0
    ratio = ratio_num / zeros  # = zero_weight / win_weight, exact rational
    win_weight, zero_weight = ratio.denominator, ratio.numerator
    common = gcd(win_weight, zero_weight) or 1
    win_weight, zero_weight = win_weight // common, zero_weight // common
    if win_weight * wins + zero_weight * zeros > UINT64_MAX:
        raise ValueError("Exact weights overflow uint64.")
    return win_weight, zero_weight


def published_statistics(payouts_cents, win_weight, zero_weight, cost=1.0):
    """Exact RTP and hit rate of the weighted lookup table."""
    weights = [win_weight if p > 0 else zero_weight for p in payouts_cents]
    total_weight = sum(weights)
    rtp = Fraction(sum(w * p for w, p in zip(weights, payouts_cents)), 100) / (total_weight * Fraction(str(cost)))
    hit_rate = Fraction(sum(w for w, p in zip(weights, payouts_cents) if p > 0), total_weight)
    return {"rtp": rtp, "hit_rate": hit_rate, "total_weight": total_weight}


def write_weighted_lookup(base_lookup_path, out_path, target_rtp, cost=1.0):
    """Read the unit-weight lookup table (id,1,payout) and write the weighted
    one. Returns the weights and exact published statistics."""
    rows = []
    with open(base_lookup_path, encoding="utf-8") as stream:
        for line in stream:
            book_id, weight, payout = line.strip().split(",")
            if int(weight) != 1:
                raise ValueError(f"Expected a unit-weight lookup table, found weight {weight} for book {book_id}.")
            rows.append((int(book_id), int(payout)))
    payouts = [p for _, p in rows]
    win_weight, zero_weight = zero_win_weights(payouts, target_rtp, cost)
    with open(out_path, "w", encoding="utf-8") as stream:
        for book_id, payout in rows:
            stream.write(f"{book_id},{win_weight if payout > 0 else zero_weight},{payout}\n")
    stats = published_statistics(payouts, win_weight, zero_weight, cost)
    return {"win_weight": win_weight, "zero_weight": zero_weight, "books": len(rows),
            "winning_books": sum(1 for p in payouts if p > 0), **stats}


# --------------------------------------------------------------------------
# V0.3.21 -- class weights for the NATURAL / GOLDEN / WINCAP distributions
# --------------------------------------------------------------------------
#
# The number of books of a class is NOT its production probability. Golden
# and cap books are generated by forced criteria (rejection sampling in
# GameState.check_repeat), in numbers chosen for statistical resolution; their
# probability comes only from the lookup weights below:
#
#   P(class) = class weight total / library weight total
#
# Classes are defined by what a book IS, not by its generation criteria:
#   natural: criteria "natural" (Golden never rolls); zero-win and winning
#            books get one weight each, exactly as in V0.3.20;
#   golden : books generated with a forced Golden Mega Fly whose payout is
#            below the cap, equal weights inside the class;
#   cap    : every book paying exactly the wincap (whichever criteria made
#            it), equal weights inside the class.
# Class masses: P(golden-or-cap round) = f * g (f = P(N5), g = P(Golden | N5)),
# of which a fraction c (= P(payout == cap | Golden), measured on the N5
# payout distribution) is the cap class.


def class_weights(natural_payouts, golden_payouts, cap_books, golden_mass, cap_mass, cap_payout,
                  target_rtp, cost=1.0, win_weight=2**36):
    """Integer weights for the three classes (payouts and cap_payout in
    hundredths of the bet). `golden_mass`/`cap_mass` are the target
    production probabilities (Fractions) of the golden and cap classes.

    The natural winning books all get `win_weight`; the natural zero-win
    weight is then solved so the published RTP hits `target_rtp` (to within
    one integer step of the zero weight, reported as `rtp_error`)."""
    golden_mass, cap_mass = Fraction(golden_mass), Fraction(cap_mass)
    if not (0 < cap_mass and 0 <= golden_mass and golden_mass + cap_mass < 1):
        raise ValueError("Invalid class masses.")
    if cap_books < 1 and cap_mass > 0:
        raise ValueError("A positive cap mass needs at least one cap book.")
    target = Fraction(str(target_rtp)) * Fraction(str(cost))
    n_win = sum(1 for p in natural_payouts if p > 0)
    n_zero = len(natural_payouts) - n_win
    if n_win == 0 or n_zero == 0:
        raise ValueError("Natural class needs both winning and zero-win books.")
    natural_mass = 1 - golden_mass - cap_mass
    rho_g, rho_c = golden_mass / natural_mass, cap_mass / natural_mass
    sum_n, sum_g = sum(natural_payouts), sum(golden_payouts)
    k_g = len(golden_payouts)
    if golden_mass > 0 and k_g == 0:
        raise ValueError("A positive golden mass needs golden books.")
    mean_g = Fraction(sum_g, k_g) if k_g else Fraction(0)
    # RTP balance, X = natural weight total:
    #   sum_n*w + rho_g*X*mean_g + rho_c*X*cap = 100*target*X*(1 + rho_g + rho_c)
    denominator = 100 * target * (1 + rho_g + rho_c) - rho_g * mean_g - rho_c * cap_payout
    if denominator <= 0:
        raise ValueError("Golden/cap classes alone exceed the RTP target.")
    natural_total = Fraction(sum_n * win_weight) / denominator
    zero_exact = (natural_total - n_win * win_weight) / n_zero
    if zero_exact < 1:
        raise ValueError("Target RTP not reachable with positive zero-win weight.")

    def build(zero_weight):
        x = n_win * win_weight + n_zero * zero_weight
        golden_each = max(1, round(rho_g * x / k_g)) if k_g else 0
        cap_each = max(1, round(rho_c * x / cap_books))
        total = x + golden_each * k_g + cap_each * cap_books
        paid = sum_n * win_weight + golden_each * sum_g + cap_each * cap_books * cap_payout
        rtp = Fraction(paid, 100) / (total * Fraction(str(cost)))
        return golden_each, cap_each, total, rtp

    zero_weight = max(1, round(zero_exact))
    best = None
    for candidate in range(max(1, zero_weight - 2), zero_weight + 3):
        golden_each, cap_each, total, rtp = build(candidate)
        err = abs(rtp - target)
        if best is None or err < best[0]:
            best = (err, candidate, golden_each, cap_each, total, rtp)
    err, zero_weight, golden_each, cap_each, total, rtp = best
    if total > UINT64_MAX:
        raise ValueError("Class weights overflow uint64.")
    return {
        "win_weight": win_weight, "zero_weight": zero_weight, "golden_weight": golden_each,
        "cap_weight": cap_each, "total_weight": total, "rtp": rtp, "rtp_error": err,
        "golden_probability": Fraction(golden_each * k_g, total),
        "cap_probability": Fraction(cap_each * cap_books, total),
        "natural_hit_rate_weight": Fraction(n_win * win_weight, total),
    }


def class_weights_by_n5_rate(natural_payouts, natural_n5_books, golden_payouts, cap_books, golden_given_n5,
                             cap_given_golden, cap_payout, target_rtp, cost=1.0, win_weight=2**36):
    """FINAL V0.3.21 weighting: P(Golden | N5) = `golden_given_n5` (exactly,
    up to integer rounding of the per-book weights) and P(cap | Golden) =
    `cap_given_golden`, defined directly on weights so it does not depend on the
    RTP solution:

        Golden total weight G = natural_N5_weight * p / (1 - p),  p = P(Golden | N5)

    because every Golden round is an N5 round and every natural N5 book wins
    (progression needs wins), so natural N5 weight = natural_n5_books * win_weight.
    The cap books take cap_given_golden * G, the other Golden books the rest.
    Only the natural zero-win weight is then solved for the target RTP (the
    existing V0.3.20 absorption), so every winning outcome keeps its relative
    frequency. Payouts in hundredths of the bet."""
    p, c = Fraction(golden_given_n5), Fraction(cap_given_golden)
    target = Fraction(str(target_rtp)) * Fraction(str(cost))
    n_win = sum(1 for x in natural_payouts if x > 0)
    n_zero = len(natural_payouts) - n_win
    k_g = len(golden_payouts)
    if n_win == 0 or n_zero == 0 or k_g == 0 or cap_books == 0 or not 0 < p < 1:
        raise ValueError("Invalid class inputs.")
    natural_n5_weight = natural_n5_books * win_weight
    golden_total = Fraction(natural_n5_weight) * p / (1 - p)
    cap_total = golden_total * c
    golden_each = max(1, round((golden_total - cap_total) / k_g))
    cap_each = max(1, round(cap_total / cap_books))
    golden_weight_total = golden_each * k_g + cap_each * cap_books
    sum_n, sum_g = sum(natural_payouts), sum(golden_payouts)
    golden_paid = golden_each * sum_g + cap_each * cap_books * cap_payout
    total_exact = Fraction(sum_n * win_weight + golden_paid) / (100 * target)
    zero_exact = (total_exact - n_win * win_weight - golden_weight_total) / n_zero
    if zero_exact < 1:
        raise ValueError("Target RTP not reachable with a positive zero-win weight.")

    def build(zero_weight):
        total = n_win * win_weight + n_zero * zero_weight + golden_weight_total
        rtp = Fraction(sum_n * win_weight + golden_paid, 100) / (total * Fraction(str(cost)))
        return total, rtp

    best = None
    for zero_weight in range(max(1, round(zero_exact) - 2), round(zero_exact) + 3):
        total, rtp = build(zero_weight)
        if best is None or abs(rtp - target) < best[0]:
            best = (abs(rtp - target), zero_weight, total, rtp)
    err, zero_weight, total, rtp = best
    if total > UINT64_MAX:
        raise ValueError("Class weights overflow uint64.")
    n5_weight = natural_n5_weight + golden_weight_total
    return {
        "win_weight": win_weight, "zero_weight": zero_weight, "golden_weight": golden_each, "cap_weight": cap_each,
        "total_weight": total, "rtp": rtp, "rtp_error": err,
        "golden_given_n5": Fraction(golden_weight_total, n5_weight),
        "cap_given_golden": Fraction(cap_each * cap_books, golden_weight_total),
        "golden_probability": Fraction(golden_each * k_g, total),
        "cap_probability": Fraction(cap_each * cap_books, total),
        "natural_hit_rate_weight": Fraction(n_win * win_weight, total),
    }


# --------------------------------------------------------------------------
# V0.3.22 -- Bonus Buy weights (mode "bonus_buy", cost 100x, B1 correction)
# --------------------------------------------------------------------------
#
# A purchased round is a complete natural round that reached N5. The mode's
# library holds three physical classes whose production probabilities come
# ONLY from these weights (never from book counts):
#   normal : natural N5 rounds without Golden, total mass (1 - p) * mass;
#   golden : forced-Golden rounds below the cap, mass p * (1 - c) * mass;
#   cap    : forced-Golden rounds paid exactly the wincap, mass p * c * mass;
# with p = P(Golden) = 1/10,000 and c = P(cap | Golden), both EXACT.
#
# B1 (product decision 2026-10-12) lowers the NORMAL weights smoothly with the
# payout so the published RTP equals the target: w_i ~ exp(-lambda * (y_i - mean)).
# It is the minimal-information-loss (KL) reweighting for a given mean shift.
# The golden and cap books keep equal weights inside their class, so the
# Golden ladder, its mean and the cap probability are untouched.

BONUS_BUY_GOLDEN_MASS = 10**13  # total golden-class weight; normal class = 9,999x this (< uint64)


def _apportion(total, scores):
    """Integer weights proportional to `scores` (floats >= 0) summing to
    exactly `total` (largest-remainder rule, deterministic)."""
    scaled = [int(round(s * 2**40)) for s in scores]
    denominator = sum(scaled)
    base = [x * total // denominator for x in scaled]
    remainder = total - sum(base)
    order = sorted(range(len(scaled)), key=lambda i: (-(scaled[i] * total % denominator), i))
    for i in order[:remainder]:
        base[i] += 1
    return base


def _golden_class_mean(golden_payouts, cap_payout, cap_given_golden):
    k = len(golden_payouts)
    return (1 - float(cap_given_golden)) * (sum(golden_payouts) / k) + float(cap_given_golden) * cap_payout


def solve_b1_lambda(normal_payouts, golden_payouts, cap_payout, golden_given_buy, cap_given_golden, target_rtp, cost):
    """lambda such that the mixture mean payout (hundredths of the bet)
    / (100 * cost) equals `target_rtp`. Plain float bisection; the exact
    integer RTP is recomputed with Fractions by bonus_buy_weights()."""
    import math
    p = float(golden_given_buy)
    y = [x / 100 for x in normal_payouts]
    ybar = sum(y) / len(y)
    mean_g = _golden_class_mean(golden_payouts, cap_payout, cap_given_golden) / 100
    target_mean = float(Fraction(str(target_rtp)) * Fraction(str(cost)))

    def mixture_mean(lam):
        f = [math.exp(-lam * (v - ybar)) for v in y]
        return (1 - p) * sum(a * v for a, v in zip(f, y)) / sum(f) + p * mean_g

    lo, hi = -2e-2, 2e-2
    if (mixture_mean(lo) - target_mean) * (mixture_mean(hi) - target_mean) > 0:
        raise ValueError("Target RTP not reachable by an exponential tilt in [-2e-2, 2e-2].")
    for _ in range(200):
        mid = (lo + hi) / 2
        if (mixture_mean(lo) - target_mean) * (mixture_mean(mid) - target_mean) <= 0:
            hi = mid
        else:
            lo = mid
    return (lo + hi) / 2, ybar


def bonus_buy_weights(normal_payouts, golden_payouts, cap_books, cap_payout, golden_given_buy=Fraction(1, 10_000),
                      cap_given_golden=Fraction(1_954_668, 20_000_000), target_rtp=0.965, cost=100.0,
                      golden_mass=BONUS_BUY_GOLDEN_MASS):
    """Exact integer weights for the "bonus_buy" lookup table. Payouts are the
    books' payoutMultiplier values (hundredths of the bet). `golden_payouts`
    are the golden books paying less than the cap; `cap_books` counts those
    paying exactly `cap_payout`. Returns lambda, the three weight lists (same
    order as the inputs) and the exact published statistics."""
    p, c = Fraction(golden_given_buy), Fraction(cap_given_golden)
    if not (0 < p < 1 and 0 < c < 1) or not normal_payouts or not golden_payouts or cap_books < 1:
        raise ValueError("Invalid Bonus Buy class inputs.")
    cap_mass = c * golden_mass
    if cap_mass.denominator != 1:
        raise ValueError("golden_mass must make the cap mass an integer.")
    cap_mass = int(cap_mass)
    normal_mass = Fraction(golden_mass) * (1 - p) / p
    if normal_mass.denominator != 1:
        raise ValueError("golden_mass must make the normal mass an integer.")
    normal_mass = int(normal_mass)
    lam, ybar = solve_b1_lambda(normal_payouts, golden_payouts, cap_payout, p, c, target_rtp, cost)
    import math
    normal_w = _apportion(normal_mass, [math.exp(-lam * (v / 100 - ybar)) for v in normal_payouts])
    golden_w = _apportion(golden_mass - cap_mass, [1.0] * len(golden_payouts))
    cap_w = _apportion(cap_mass, [1.0] * cap_books)
    total = sum(normal_w) + sum(golden_w) + sum(cap_w)
    if total > UINT64_MAX:
        raise ValueError("Bonus Buy weights overflow uint64.")
    paid = (sum(w * x for w, x in zip(normal_w, normal_payouts)) + sum(w * x for w, x in zip(golden_w, golden_payouts))
            + sum(cap_w) * cap_payout)
    return {
        "lambda": lam, "normal_weights": normal_w, "golden_weights": golden_w, "cap_weights": cap_w,
        "total_weight": total,
        "rtp": Fraction(paid, 100) / (total * Fraction(str(cost))),
        "golden_probability": Fraction(sum(golden_w) + sum(cap_w), total),
        "cap_given_golden": Fraction(sum(cap_w), sum(golden_w) + sum(cap_w)),
    }
